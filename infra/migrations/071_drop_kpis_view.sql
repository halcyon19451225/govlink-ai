-- ================================================================
-- Migration 071: 互換ビュー kpis を落とす（正本を1つにする）
-- ================================================================
--
-- 設計: claude/coe-dataset-model.md §9-1 Step 4（読み取りの切替が済んだらビューを落とす）
--
-- ⚠ **適用の順序が、いつもと逆。**
-- ----------------------------------------------------------------
--   ふつうの migration は「先に当ててからデプロイ」する（テーブルが無い状態で
--   新しいコードが動くと落ちるため。`claude/coe-rate-limit.md` §5）。
--   **これは逆で、先にデプロイしてから当てる。**
--   落とすのは「いま動いているコードが使っているもの」だからで、
--   デプロイより先に当てると、旧コードが動いている間ずっと画面が落ちる。
--
--   正しい順序:
--     ① READ-1（読み取りを実体へ切り替えたコミット）を push
--     ② Amplify のデプロイが終わったことを確認する
--     ③ この migration を当てる
--
--   ②を飛ばさないこと。`npm run rehearse 071` は通ってしまうが（構文は正しい）、
--   通ることと、当ててよいことは別。
--
-- 何を落とすか
-- ----------------------------------------------------------------
--   1. ビュー `kpis` … 069 で指標は `indicators` に吸収された。読み取り側（47ファイル・
--      60か所）は READ-1 で実体を読むようになったので、ビューの役目は終わった。
--      残しておくと「どちらを読めばいいのか」が生まれ、二重の正本に戻る
--   2. `measure_indicators.kpi_id` … 069 で `indicator_id` に置き換わった。
--      コードからの参照はゼロ（`check:indicator` が構造で見ている）

-- ────────────────────────────────────────────────────────────────
-- 1. 互換ビューを落とす
-- ────────────────────────────────────────────────────────────────
DROP VIEW IF EXISTS kpis;

-- ────────────────────────────────────────────────────────────────
-- 2. 割当表から、置き換わった列を落とす
-- ────────────────────────────────────────────────────────────────
--   069 の 4-3 で、この列の中身は measure_indicators.indicator_id に移した
--   （kpi_id を持つ行はそれを使い、持たない行は指標を起こして結んだ）。
ALTER TABLE measure_indicators DROP COLUMN IF EXISTS kpi_id;

COMMENT ON COLUMN measure_indicators.indicator_id IS
  '指標の実体。ラベル・単位・データソース・頻度・基準日はこちらが正本（071 で kpi_id を落とした）';

-- ────────────────────────────────────────────────────────────────
-- 3. 落とし忘れの確認
-- ────────────────────────────────────────────────────────────────
DO $$
BEGIN
  IF to_regclass('public.kpis') IS NOT NULL THEN
    RAISE EXCEPTION 'kpis がまだ残っています（ビューではなく実体が存在する可能性）';
  END IF;
  RAISE NOTICE '互換ビュー kpis を落としました。指標の正本は indicators / indicator_targets / indicator_values です';
END $$;
