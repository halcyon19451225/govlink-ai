/**
 * 評価報告書の様式（CA2-5改）
 *
 * 正本は `claude/coe-eval-report-forms.md`（政策評価・次期計画反映 報告書様式集）。
 * ここはその**様式の定義だけ**を持ち、データの取り出し（reportData.ts）と
 * docx の組み立て（reportDocx.ts）から切り離してある。
 *
 * 様式集の構造:
 *   様式F7-0 共通ヘッダ（①〜⑦）… 全報告書の冒頭。③〜⑥を入れれば
 *     評価過程（記号列）・財政効果率・反映ルートは機械的に定まる（報告書の自動分岐）
 *   報告書No.1〜9        … 共通ヘッダに続く5ブロック
 *     A 判定の意味（定型・編集不要）
 *     B 課題整理（定型文・空欄記入式）
 *     C 対策立案の観点（推奨フレームワークと手順。用いない場合は代替根拠をC欄に記す）
 *     D 次期計画への反映（反映先①〜⑤の指定）
 *     E 留意点
 *
 * 取組評価（年次・担当者レベル）は様式集のNo.1〜9の対象ではない。
 * ただし共通ヘッダ④が「初期アウトカムの年次履歴は、実行起因／論理起因の切り分けの
 * **唯一の根拠**」と定めている以上、取組評価報告書は
 * 「実施できたか（実行）／実施したが変化がなかったか（論理）」を必ず残す形にする。
 * この切り分けが期末（主要施策評価）でNo.1のB欄の起点になる。
 *
 * 様式は差し替え前提。様式を替えるときは**このファイルだけ**を書き替える。
 */

import { REPORT_PATTERNS, type ReportNo } from "@/lib/evaluation/judgment";

export type ReportKind = "work" | "measure";

/** 記述欄に流し込む本文の種類（program_evaluations の列に対応） */
export type NarrativeField =
  | "findings"
  | "barrier_factors"
  | "improvement_actions"
  | "next_steps"
  | "result";

/** 節の中身の種類 — reportDocx がこの種別で描き分ける */
export type ReportBlockKind =
  | "text" // 記述（fields で本文の出どころを指定）
  | "kv" // 見出し付きの1行項目の並び（様式F7-0 ①）
  | "judgment" // 様式F7-0 ② 評価過程（記号列・報告書No.・ルート・標準処遇）
  | "outcome_summary" // 様式F7-0 ③ 成果（基準値・目標・実績・ベースライン・X・比較の段）
  | "indicator_table" // 指標の実績表（基準値・目標・実績・判定・出所）
  | "annual_history" // 様式F7-0 ④ 初期アウトカムの年次履歴（＝取組評価の集約）
  | "cost_table" // 様式F7-0 ⑤ 事業費（年度別・財源内訳）
  | "fiscal_effect" // 様式F7-0 ⑥ 財政効果率（寄与経路・推計・判定）
  | "treatment" // 様式F7-0 ⑦ 処遇（ルート・標準処遇・決定処遇・理由書の有無）
  | "pattern_meaning" // 報告書A欄 判定の意味（定型）
  | "framework_guide" // 報告書C欄 推奨フレームワークと手順
  | "reflect_targets" // 報告書D欄 次期計画への反映先
  | "pattern_caution" // 報告書E欄 留意点（定型）
  | "path_table" // 判定経路（工程・問い・回答・補足）
  | "delegation_table" // 委任した／された課題
  | "work_rollup_table" // 取組評価のロールアップ（主要施策評価のみ）
  | "benchmark_table" // 他団体比較（比較の段の裏づけ）
  | "activity_table"; // 実施記録（アウトプット。取組評価のみ）

export interface ReportBlock {
  kind: ReportBlockKind;
  /** データが空のとき、節ごと省略するか（false なら「該当なし」と出す） */
  omitWhenEmpty?: boolean;
  /** kind = "text" のとき、どの記述を流すか */
  fields?: NarrativeField[];
}

export interface ReportSection {
  /** 様式上の欄記号（①〜⑦ ／ A〜E） */
  mark: string;
  heading: string;
  /** 記入要領。空欄のまま提出されないよう、報告書にも小さく刷る */
  note?: string;
  blocks: ReportBlock[];
}

export interface ReportForm {
  kind: ReportKind;
  title: string;
  subtitle: string;
  sections: ReportSection[];
}

