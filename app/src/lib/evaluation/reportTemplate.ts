/** A欄（判定の意味）— 判定から機械生成する定型文 */
export function patternMeaningText(no: ReportNo): string {
  const p = REPORT_PATTERNS[no];
  return [
    `評価過程 ${p.marks}（報告書No.${p.no}「${p.title}」）。`,
    `状態の意味: ${p.state}。`,
    `反映ルート: ${p.route} ${p.route === "A" ? "校正" : p.route === "B" ? "再設計" : p.route === "C" ? "移植" : "構造"}。`,
    `標準処遇: ${p.standardTreatment}。`,
    "標準処遇は初期値であり、異なる決定を採る場合は理由書（様式H4）を要する。",
  ].join("");
}

